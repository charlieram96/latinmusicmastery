export function adminLabel(text: string, locale: Locale): string {
  const value = locale === 'es' ? ADMIN_LABELS[text] ?? text : text
  return value.replace(/&(?:rsquo|apos|#39);/g, "'").replace(/&amp;/g, '&').replace(/&middot;/g, '·').replace(/&mdash;/g, '—').replace(/&gt;/g, '>')
}
