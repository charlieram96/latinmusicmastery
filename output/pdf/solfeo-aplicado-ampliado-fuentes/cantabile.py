def compose_bars(number,notes,meter):
 cells=MELODIES[number-1].replace('/',' ').split();assert len(cells)==16
 bars=[]
 for j,cell in enumerate(cells):
  ds=RHYTHMS[meter][len(cell)]
  if number==7 and len(cell)==2 and j!=15:ds=[(4,True),8]
  if number==8 and len(cell)==4:ds=[8,4,8,2]
  events=[]
  for degree,d in zip(cell,ds):
   dur,dotted=d if isinstance(d,tuple) else (d,False)
   events.append(N(notes[int(degree)-1],dur,**({'dot':True} if dotted else {})))
  if number in (4,6,10,13,17,19) and j in (3,7) and len(events)==1:
   # A cadential tone followed by a measured breath.
   pitch=events[0]['pitch']
   events=[N(pitch,4),RS(4)] if meter=='2/4' else [N(pitch,2),RS(4)] if meter=='3/4' else [N(pitch,2),RS(2)]
  bars.append(events)
 return bars
